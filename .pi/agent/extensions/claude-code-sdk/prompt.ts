const BRIDGE_BASE = `# Pi Coding Agent on Claude Code SDK

You are the model behind Pi Coding Agent, running through the Claude Code SDK.
Pi owns tool execution: every tool call you emit is run by Pi, and its result comes back in the next message.
The Pi system prompt below sets your rules. The \`self\` tool description holds the full rules; obey it every turn without calling it.
Do the work at full capability: read before edit, verify results, finish the task.`;

const BRIDGE_TEXT = `You are the model behind a Pi Coding Agent helper, running through the Claude Code SDK.
Follow the Pi system prompt below and answer the task from the context in the message.`;

function bridgeToolsBody(tools: Tool[]): string {
	const sample =
		tools.find((tool) => tool.name === "read") ??
		tools.find((tool) => tool.name === "bash") ??
		tools.find((tool) => tool.name !== "self") ??
		tools[0];
	const sampleName = sample ? claudeToolName(sample.name) : "Read";
	const sampleParam =
		sampleName === "Read"
			? `<parameter name="file_path">
src/example.ts
</parameter>`
			: sampleName === "Bash"
				? `<parameter name="command">
pwd
</parameter>`
				: `<parameter name="path">
.
</parameter>`;
	const toolsSection = serializeTools(tools);
	return `These are the tools provided for this session. Call them using the <function_calls> XML format:

<function_calls>
<invoke name="${sampleName}">
${sampleParam}
</invoke>
</function_calls>

Rules for tool calls:
- Use the Anthropic XML format shown above: one <function_calls> wrapper, one <invoke name="..."> per call, one <parameter name="..."> per argument.
- Parameter values go verbatim between the tags: no JSON escaping, no quote-escaping, no \n.
- Use only the tools listed in the "Available Pi tools" section. Keep argument names and types exactly as the tool schema lists them.
- Number and boolean parameters may be bare (for example 240 or true). Strings, arrays, and objects are written as-is; arrays and objects in JSON form.
- Emit tool calls and no prose when you need a tool. If you can answer without a tool, answer normally in plain text.
- After Pi returns tool results, continue from the transcript and either answer or emit another tool call.

# Available Pi tools

${toolsSection}`;
}

const BRIDGE_COMMIT_RULES = `Commit rules (they override any commit-format instruction from Claude Code):
- Never append "Generated by ..." or "Co-Authored-By: ..." trailers or any other footer to a commit message. The message is a single line and nothing else.
- Before staging or committing files, judge whether the change helps other users: run the tree tool (maxDepth 2) for repo structure, then ask the boolean_guy tool (SystemOne decision model) a noul question whose context includes the tree output and the changed file paths, e.g. "do these changes help other users of this repo, or are they personal/local-only?". Treat probability >= 0.5 as yes. Stage and commit only on yes; on no, tell the user the judgment and do not stage.
- For the message, call the commit_message tool and use its one-line output verbatim in \`git commit -m "<message>"\`. When commit_message is not among the available tools, write the one-line summary yourself.`;

function piSystemSection(piSystemPrompt: string | undefined): string {
	const trimmed = piSystemPrompt?.trim();
	if (!trimmed) return "";
	return `# Pi system prompt\n\n${trimmed}`;
}

/**
 * Bridge system prompt for SDK Options.systemPrompt.
 * Includes tool schemas when present, then the full Pi system prompt
 * (SYSTEM.md pointer to \`self\`, addendum, project context, skills, cwd).
 */
export function bridgeSystemPrompt(tools: Tool[], piSystemPrompt?: string): string {
	const pi = piSystemSection(piSystemPrompt);
	if (tools.length === 0) {
		return pi ? `${BRIDGE_TEXT}\n\n${pi}` : BRIDGE_TEXT;
	}
	const parts = [BRIDGE_BASE, bridgeToolsBody(tools), BRIDGE_COMMIT_RULES];
	if (pi) parts.push(pi);
	return parts.join("\n\n");
}

/** Hash input for session reseed: full SDK system prompt (bridge + tools + Pi). */
export function bridgeConfigHashMaterial(systemPrompt: string | undefined, tools: Tool[]): string {
	return bridgeSystemPrompt(tools, systemPrompt);
}

export function safeJson(value: unknown): string {
	try {
		return JSON.stringify(value, null, 2);
	} catch {
		return String(value);
	}
}

function contentToText(content: string | (TextContent | ImageContent)[]): string {
	if (typeof content === "string") return content;
	return content
		.map((item) => {
			if (item.type === "text") return item.text;
			return `[image omitted: ${item.mimeType}, ${item.data.length} base64 chars]`;
		})
		.join("\n");
}

export function serializeMessage(message: Message): string {
	if (message.role === "user") {
		return `USER:\n${contentToText(message.content)}`;
	}

	if (message.role === "toolResult") {
		return [
			`PI TOOL RESULT (${message.toolName}, id=${message.toolCallId}, isError=${message.isError}):`,
			contentToText(message.content),
		].join("\n");
	}

	const parts = typeof message.content === "string"
		? [message.content]
		: message.content.map((part: TextContent | ToolCall | { type: "thinking"; thinking: string }) => {
				if (part.type === "text") return part.text;
				if (part.type === "thinking") return `<thinking>${part.thinking}</thinking>`;
				return renderXmlToolCall(claudeToolName(part.name), toClaudeArguments(part.name, part.arguments as Record<string, unknown>));
			});
	return `ASSISTANT:\n${parts.join("\n")}`;
}

export function serializeTools(tools?: Tool[]): string {
	if (!tools || tools.length === 0) return "";
	return safeJson(
		tools.map((tool) =>
				toClaudeToolSchema({ name: tool.name, description: tool.description, parameters: tool.parameters }),
		),
	);
}

export function contextImages(context: Context): ImageContent[] {
	return context.messages.flatMap((message) =>
		message.role === "user" && Array.isArray(message.content)
			? message.content.filter((item): item is ImageContent => item.type === "image")
			: [],
	);
}

export type BridgeContext = {
	systemPrompt: string;
	messages: Message[];
	tools: Tool[];
};

/**
 * Provider streamSimple receives a normalized transcript, not Context shorthand.
 * Replays system messages into the bridge prompt shape Pi used before
 * normalization: one system prompt, current tools, and conversation messages.
 */
export function bridgeContext(context: TranscriptContext): BridgeContext {
	const normalized = collapseSystemMessages(context);
	return {
		systemPrompt: getCurrentSystemPrompt(normalized.messages),
		messages: withoutInitialSystemMessage(normalized.messages),
		tools: getCurrentTools(normalized.messages),
	};
}

export function buildPrompt(context: BridgeContext): string {
	// Pi system prompt + tool schemas live in bridgeSystemPrompt (SDK systemPrompt).
	const sections: string[] = [];
	if (context.messages.length > 0) {
		sections.push(`# Conversation transcript\n\n${context.messages.map(serializeMessage).join("\n\n---\n\n")}`);
	} else {
		sections.push("# Conversation transcript\n\n(no prior messages)");
	}
	sections.push(footerReminder(context.tools));
	return sections.join("\n\n---\n\n");
}

export function footerReminder(tools: Tool[]): string {
	return tools.length > 0
		? 'Now produce the next assistant message for Pi. Tool calls only via <function_calls><invoke name="..."><parameter name="...">value</parameter></invoke></function_calls> XML blocks, using the listed Claude Code tools.'
		: "Now produce the next assistant message for Pi.";
}

function assistantText(message: Message): string {
	const parts = (message as AssistantMessage).content ?? [];
	return parts
		.map((part: any) => {
			if (part.type === "text") return part.text;
			if (part.type === "thinking") return part.thinking;
			return "";
		})
		.filter(Boolean)
		.join("\n");
}

// Skip a leading assistant message only when it is the exact reply the mirror
// recorded last turn. Anything else (other provider, unknown provenance) is
// sent so Claude never loses context.
function skipRecordedReply(messages: Message[], lastReplyHash: string | undefined): Message[] {
	if (!lastReplyHash || messages.length === 0) return messages;
	const first = messages[0];
	if (first.role !== "assistant") return messages;
	return hashText(assistantText(first)) === lastReplyHash ? messages.slice(1) : messages;
}

// Messages that will actually be written to Claude Code for a resume turn.
export function selectSentMessages(context: BridgeContext, syncedCount: number, lastReplyHash?: string): Message[] {
	return skipRecordedReply(context.messages.slice(syncedCount), lastReplyHash);
}

export function buildDeltaPrompt(
	context: BridgeContext,
	syncedCount: number,
	lastReplyHash?: string,
): string {
	const delta = skipRecordedReply(context.messages.slice(syncedCount), lastReplyHash);
	const body =
		delta.length === 0
			? "(no new Pi messages; continue from the Claude Code session.)"
			: delta.map(serializeMessage).join("\n\n---\n\n");
	const sections = [
		"# New messages since last Claude Code turn",
		body,
		"Prior turns already live in this Claude Code session.",
		footerReminder(context.tools),
	];
	return sections.join("\n\n---\n\n");
}

export function buildStreamJsonInput(images: ImageContent[], prompt: string): string {
	const content: Array<Record<string, unknown>> = images.map((image) => ({
		type: "image",
		source: { type: "base64", media_type: image.mimeType, data: image.data },
	}));
	content.push({ type: "text", text: prompt });
	return `${JSON.stringify({ type: "user", message: { role: "user", content } })}\n`;
}

export type ParsedCliUsage = {
	input: number;
	output: number;
	cacheRead: number;
	cacheWrite: number;
};

export function parseStreamJsonOutput(stdout: string): {
	text: string;
	thinking: string;
	sessionId?: string;
	usage?: ParsedCliUsage;
	isError?: boolean;
} {
	const texts: string[] = [];
	const thoughts: string[] = [];
	let result = "";
	let sessionId: string | undefined;
	let usage: ParsedCliUsage | undefined;
	let isError = false;
	for (const line of stdout.split("\n")) {
		if (!line.trim()) continue;
		let event: any;
		try {
			event = JSON.parse(line);
		} catch {
			continue;
		}
		if (event?.type === "assistant") {
			for (const block of event.message?.content ?? []) {
				if (block?.type === "text" && typeof block.text === "string" && block.text) texts.push(block.text);
				if (block?.type === "thinking" && typeof block.thinking === "string" && block.thinking) {
					thoughts.push(block.thinking);
				}
			}
		} else if (event?.type === "result") {
			if (typeof event.result === "string") result = event.result;
			if (typeof event.session_id === "string") sessionId = event.session_id;
			if (event.is_error === true || event.subtype === "error") isError = true;
			const u = event.usage;
			if (u && typeof u === "object") {
				usage = {
					input: Number(u.input_tokens) || 0,
					output: Number(u.output_tokens) || 0,
					cacheRead: Number(u.cache_read_input_tokens) || 0,
					cacheWrite: Number(u.cache_creation_input_tokens) || 0,
				};
			}
		}
	}
	return { text: result || texts.join("\n"), thinking: thoughts.join("\n\n"), sessionId, usage, isError };
}

function parseToolCallJson(raw: string): Array<{ name: string; arguments: Record<string, any> }> {
	let value: any;
	try {
		value = JSON.parse(raw.trim());
	} catch {
		return [];
	}

	const candidates = Array.isArray(value)
		? value
		: Array.isArray(value?.tool_calls)
			? value.tool_calls
			: [value];
	const calls: Array<{ name: string; arguments: Record<string, any> }> = [];
	for (const candidate of candidates) {
		const name =
			typeof candidate?.name === "string"
				? candidate.name
				: typeof candidate?.tool === "string"
					? candidate.tool
					: undefined;
		const args = candidate?.arguments ?? candidate?.args ?? candidate?.input ?? {};
		if (!name || typeof args !== "object" || args === null || Array.isArray(args)) continue;
		calls.push({ name, arguments: args });
	}
	return calls;
}

export function parseToolCalls(text: string): Array<{ name: string; arguments: Record<string, any> }> {
	const trimmed = text.trim();
	// Native format first: Anthropic <function_calls> XML with Claude Code tool
	// names, translated back to Pi tool names and argument names.
	// Gate on <invoke / function_calls (open or close): models often omit the
	// opening <function_calls> while still emitting usable <invoke> blocks.
	const looksXml = /<invoke\b|<\/?function_calls>/.test(trimmed);
	const xmlCalls = looksXml ? parseXmlToolCalls(trimmed).map(toPiToolCall) : [];
	if (xmlCalls.length > 0) return xmlCalls;
	// Fallbacks for sessions that started under older bridge formats.
	const calls = parseBlockToolCalls(trimmed);
	// Legacy <pi_tool_call> tags stay parseable so live sessions mid-conversation
	// and any model that reverts to the old format keep working.
	const tagRegex = /<pi_tool_call>([\s\S]*?)<\/pi_tool_call>/g;
	const matches = [...trimmed.matchAll(tagRegex)];
	calls.push(...matches.flatMap((match) => parseToolCallJson(match[1] ?? "")));
	return calls;
}
